-- Chapter masters may read media attached to their own county posts so the
-- composer can hydrate existing drafts without exposing another county's work.
drop policy if exists "Chapter masters can read own post media" on public.post_media;
create policy "Chapter masters can read own post media"
on public.post_media
for select
to authenticated
using (
  exists (
    select 1
    from public.posts as post
    join public.portal_accounts as account
      on account.user_id = (select auth.uid())
     and account.role = 'chapter_master'
     and account.status = 'active'
     and account.county_id = post.county_id
    where post.id = post_media.post_id
      and post.author_user_id = (select auth.uid())
      and post.scope = 'county'
  )
);

drop policy if exists "Chapter masters can insert own post media" on public.post_media;
