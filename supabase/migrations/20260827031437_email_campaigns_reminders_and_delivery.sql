create or replace function public.rrg_subscribe_county_updates(
  p_county_id bigint,
  p_email text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_email text := lower(btrim(p_email));
  v_contact_id bigint;
  v_suppression_reason text;
begin
  if p_county_id is null or not exists (select 1 from public.counties where id = p_county_id) then
    raise exception 'A valid county is required.' using errcode = '22023';
  end if;
  if v_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' or char_length(v_email) > 320 then
    raise exception 'Enter a valid email address.' using errcode = '22023';
  end if;

  select reason into v_suppression_reason
  from public.email_suppressions
  where email = v_email;

  if v_suppression_reason in ('bounce', 'complaint', 'admin') then
    return jsonb_build_object('subscribed', false, 'reason', 'suppressed');
  end if;

  delete from public.email_suppressions where email = v_email and reason = 'unsubscribe';

  select id into v_contact_id
  from public.county_contacts
  where county_id = p_county_id and lower(btrim(email)) = v_email
  for update;

  if v_contact_id is null then
    insert into public.county_contacts (county_id, email, subscription_status, unsubscribed_at)
    values (p_county_id, v_email, 'active', null)
    returning id into v_contact_id;
  else
    update public.county_contacts
    set subscription_status = 'active', unsubscribed_at = null
    where id = v_contact_id;
  end if;

  return jsonb_build_object('subscribed', true);
exception
  when unique_violation then
    update public.county_contacts
    set subscription_status = 'active', unsubscribed_at = null
    where county_id = p_county_id and lower(btrim(email)) = v_email;
    return jsonb_build_object('subscribed', true);
end;
$$;

create or replace function public.rrg_request_followup_reminder(
  p_goal_id bigint,
  p_email text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_email text := lower(btrim(p_email));
  v_goal public.county_records_request_goals%rowtype;
  v_profile_status text;
  v_pending_count integer;
  v_reminder_id bigint;
  v_manage_token uuid;
begin
  if v_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' or char_length(v_email) > 320 then
    raise exception 'Enter a valid email address.' using errcode = '22023';
  end if;

  select * into v_goal
  from public.county_records_request_goals
  where id = p_goal_id;

  if not found or not v_goal.is_public or v_goal.locked or v_goal.request_profile_id is null then
    raise exception 'This goal is not available for reminders.' using errcode = '42501';
  end if;

  select status into v_profile_status
  from public.request_profiles
  where id = v_goal.request_profile_id;

  if v_profile_status <> 'verified' then
    raise exception 'This request profile is not available for reminders.' using errcode = '42501';
  end if;

  if exists (select 1 from public.email_suppressions where email = v_email) then
    return jsonb_build_object('scheduled', false, 'reason', 'suppressed');
  end if;

  select count(*) into v_pending_count
  from public.request_followup_reminders
  where email = v_email and status in ('pending', 'processing');

  if v_pending_count >= 3 then
    raise exception 'Too many reminders are already scheduled for this address.' using errcode = '54000';
  end if;

  select id, manage_token into v_reminder_id, v_manage_token
  from public.request_followup_reminders
  where goal_id = p_goal_id and email = v_email and status in ('pending', 'processing');

  if v_reminder_id is null then
    insert into public.request_followup_reminders (
      email, county_id, goal_id, request_profile_id, due_at
    ) values (
      v_email, v_goal.county_id, v_goal.id, v_goal.request_profile_id, now() + interval '7 days'
    ) returning id, manage_token into v_reminder_id, v_manage_token;
  end if;

  return jsonb_build_object(
    'scheduled', true,
    'due_at', (select due_at from public.request_followup_reminders where id = v_reminder_id),
    'manage_token', v_manage_token
  );
end;
$$;

create or replace function public.rrg_cancel_followup_reminder(p_manage_token uuid)
