create or replace function public.rrg_unsubscribe_email(p_token uuid)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_email text;
begin
  select recipient_email into v_email
  from public.email_deliveries
  where unsubscribe_token = p_token;

  if v_email is null then
    return false;
  end if;

  insert into public.email_suppressions (email, reason)
  values (v_email, 'unsubscribe')
  on conflict (email) do update
    set reason = 'unsubscribe', source_event_id = null, suppressed_at = now();

  update public.county_contacts
  set subscription_status = 'unsubscribed', unsubscribed_at = now()
  where lower(btrim(email)) = v_email;

  return true;
end;
$$;

create or replace function public.rrg_request_post_email_campaign(
  p_post_id bigint,
  p_subject text default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := auth.uid();
  v_account public.portal_accounts%rowtype;
  v_post public.posts%rowtype;
  v_campaign_id bigint;
  v_subject text;
begin
  if v_actor is null then
    raise exception 'Authentication required.' using errcode = '42501';
  end if;

  select * into v_account from public.portal_accounts where user_id = v_actor;
  if not found or v_account.status <> 'active' then
    raise exception 'An active portal account is required.' using errcode = '42501';
  end if;

  select * into v_post from public.posts where id = p_post_id for update;
  if not found then raise exception 'Post not found.' using errcode = 'P0002'; end if;

  if v_account.role = 'chapter_master' and (
    v_post.author_user_id <> v_actor or v_post.scope <> 'county' or v_post.county_id <> v_account.county_id
  ) then
    raise exception 'Chapter masters may email only their own county posts.' using errcode = '42501';
  elsif v_account.role <> 'admin' and v_account.role <> 'chapter_master' then
    raise exception 'Not authorized.' using errcode = '42501';
  end if;

  if v_post.status not in ('draft', 'pending', 'approved') then
    raise exception 'Only draft, pending, or approved posts may be prepared for email.' using errcode = '22023';
  end if;

  v_subject := coalesce(nullif(btrim(p_subject), ''), nullif(btrim(v_post.title), ''));
  if v_subject is null or char_length(v_subject) > 180 then
    raise exception 'Email subject must be between 1 and 180 characters.' using errcode = '22023';
  end if;

  insert into public.email_campaigns (
    post_id, requested_by, target_scope, county_id, subject
  ) values (
    v_post.id, v_actor, v_post.scope, v_post.county_id, v_subject
  ) returning id into v_campaign_id;

  update public.posts set mass_email_requested = true where id = v_post.id;

  insert into public.security_audit_events (
    actor_user_id, county_id, event_type, target_table, target_id, event_data
  ) values (
    v_actor, v_post.county_id, 'email_campaign_requested', 'email_campaigns', v_campaign_id::text,
    jsonb_build_object('post_id', v_post.id, 'scope', v_post.scope)
  );

  return v_campaign_id;
end;
$$;

create or replace function public.rrg_admin_review_email_campaign(
  p_campaign_id bigint,
  p_approve boolean,
  p_review_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := auth.uid();
  v_campaign public.email_campaigns%rowtype;
  v_post public.posts%rowtype;
  v_recipient_count integer := 0;
begin
  if v_actor is null or not exists (
    select 1 from public.portal_accounts
    where user_id = v_actor and role = 'admin' and status = 'active'
  ) then
    raise exception 'Administrator access required.' using errcode = '42501';
  end if;

  select * into v_campaign from public.email_campaigns where id = p_campaign_id for update;
  if not found then raise exception 'Campaign not found.' using errcode = 'P0002'; end if;
  if v_campaign.status <> 'requested' then
    raise exception 'Only requested campaigns may be reviewed.' using errcode = '22023';
  end if;
  if p_review_note is not null and char_length(p_review_note) > 2000 then
    raise exception 'Review note is too long.' using errcode = '22023';
  end if;

  if not p_approve then
    update public.email_campaigns
    set status = 'rejected', review_note = p_review_note, updated_at = now()
    where id = p_campaign_id;
    update public.posts set mass_email_approved = false where id = v_campaign.post_id;
  else
    select * into v_post from public.posts where id = v_campaign.post_id for share;
    if v_post.status <> 'approved' then
      raise exception 'The post must be approved before its email campaign can be approved.' using errcode = '22023';
    end if;
    if v_post.scope <> v_campaign.target_scope or v_post.county_id is distinct from v_campaign.county_id then
      raise exception 'The post audience changed after the campaign was requested.' using errcode = '22023';
    end if;

    update public.email_campaigns
    set status = 'approved', approved_by = v_actor, approved_at = now(), review_note = p_review_note,
        post_snapshot = jsonb_build_object(
          'post_id', v_post.id, 'title', v_post.title, 'summary', v_post.summary,
          'body', v_post.body, 'content_type', v_post.content_type,
          'scope', v_post.scope, 'county_id', v_post.county_id,
          'cover_image_path', v_post.cover_image_path,
          'cover_image_alt', v_post.cover_image_alt,
          'updated_at', v_post.updated_at
        ), updated_at = now()
    where id = p_campaign_id;

    insert into public.email_deliveries (campaign_id, county_id, recipient_email, status)
    select distinct p_campaign_id, cc.county_id, lower(btrim(cc.email)), 'pending'
    from public.county_contacts cc
    where cc.subscription_status = 'active'
      and (v_campaign.target_scope = 'global' or cc.county_id = v_campaign.county_id)
      and not exists (
        select 1 from public.email_suppressions s where s.email = lower(btrim(cc.email))
      )
    on conflict (campaign_id, recipient_email) do nothing;

    select count(*) into v_recipient_count
    from public.email_deliveries where campaign_id = p_campaign_id;

    update public.email_campaigns
    set recipient_count = v_recipient_count,
        status = case when v_recipient_count = 0 then 'sent' else 'approved' end,
        completed_at = case when v_recipient_count = 0 then now() else completed_at end,
        updated_at = now()
    where id = p_campaign_id;
    update public.posts set mass_email_approved = true where id = v_campaign.post_id;
  end if;

  insert into public.security_audit_events (
    actor_user_id, county_id, event_type, target_table, target_id, event_data
  ) values (
    v_actor, v_campaign.county_id,
    case when p_approve then 'email_campaign_approved' else 'email_campaign_rejected' end,
    'email_campaigns', p_campaign_id::text,
    jsonb_build_object('post_id', v_campaign.post_id, 'recipient_count', v_recipient_count)
  );

  return jsonb_build_object('approved', p_approve, 'recipient_count', v_recipient_count);
end;
$$;

create or replace function public.rrg_list_email_campaigns(
  p_status text default null,
  p_page integer default 1,
  p_page_size integer default 25
)
returns table (
  id bigint, post_id bigint, post_title text, county_id bigint, county_name text,
  target_scope text, status text, subject text, requested_at timestamptz,
  approved_at timestamptz, recipient_count integer, sent_count integer,
  delivered_count integer, bounced_count integer, complained_count integer,
  failed_count integer, total_count bigint
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := auth.uid();
  v_account public.portal_accounts%rowtype;
  v_page integer := greatest(coalesce(p_page, 1), 1);
  v_page_size integer := least(greatest(coalesce(p_page_size, 25), 1), 100);
begin
  if v_actor is null then raise exception 'Authentication required.' using errcode = '42501'; end if;
  select * into v_account from public.portal_accounts where user_id = v_actor;
  if not found or v_account.status <> 'active' then
    raise exception 'An active portal account is required.' using errcode = '42501';
  end if;

  return query
  select ec.id, ec.post_id, p.title, ec.county_id, c.name, ec.target_scope, ec.status,
         ec.subject, ec.requested_at, ec.approved_at, ec.recipient_count, ec.sent_count,
         ec.delivered_count, ec.bounced_count, ec.complained_count, ec.failed_count,
         count(*) over()
  from public.email_campaigns ec
  join public.posts p on p.id = ec.post_id
  left join public.counties c on c.id = ec.county_id
  where (p_status is null or ec.status = p_status)
    and (
      v_account.role = 'admin'
      or (v_account.role = 'chapter_master' and ec.county_id = v_account.county_id and ec.requested_by = v_actor)
    )
  order by ec.requested_at desc, ec.id desc
  limit v_page_size offset (v_page - 1) * v_page_size;
end;
$$;

create or replace function public.rrg_claim_email_deliveries(p_limit integer default 25)
returns table (
  delivery_id bigint, campaign_id bigint, recipient_email text, unsubscribe_token uuid,
  subject text, post_snapshot jsonb, county_name text, reply_to_email text
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.email_deliveries
  set status = 'failed', failed_at = now(), last_error_code = 'claim_timeout'
  where status = 'processing' and claimed_at < now() - interval '15 minutes' and attempt_count >= 3;

  return query
  with claimed as (
    select d.id
    from public.email_deliveries d
    join public.email_campaigns c on c.id = d.campaign_id
    where (d.status = 'pending' or (d.status = 'processing' and d.claimed_at < now() - interval '15 minutes'))
      and d.attempt_count < 3 and c.status in ('approved', 'sending')
    order by d.queued_at, d.id
    for update of d skip locked
    limit least(greatest(coalesce(p_limit, 25), 1), 100)
  ), updated as (
    update public.email_deliveries d
    set status = 'processing', claimed_at = now(), attempt_count = attempt_count + 1
    from claimed
    where d.id = claimed.id
    returning d.*
  )
  select u.id, u.campaign_id, u.recipient_email, u.unsubscribe_token,
         c.subject, c.post_snapshot, co.name,
         coalesce(nullif(btrim(co.chapter_contact_email), ''), 'rerouter@flockblocktn.org')
  from updated u
  join public.email_campaigns c on c.id = u.campaign_id
  join public.counties co on co.id = u.county_id;

  update public.email_campaigns c
  set status = 'sending', send_started_at = coalesce(send_started_at, now()), updated_at = now()
  where c.status = 'approved'
    and exists (select 1 from public.email_deliveries d where d.campaign_id = c.id and d.status = 'processing');
end;
$$;

create or replace function public.rrg_record_email_delivery_result(
  p_delivery_id bigint,
  p_sent boolean,
  p_provider_email_id text default null,
  p_error_code text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_campaign_id bigint;
begin
  update public.email_deliveries
  set status = case when p_sent then 'sent' else 'failed' end,
      provider_email_id = case when p_sent then p_provider_email_id else provider_email_id end,
      sent_at = case when p_sent then now() else sent_at end,
      failed_at = case when p_sent then failed_at else now() end,
      last_error_code = case when p_sent then null else left(coalesce(p_error_code, 'send_failed'), 80) end
  where id = p_delivery_id and status = 'processing'
  returning campaign_id into v_campaign_id;

  if v_campaign_id is null then return; end if;

  update public.email_campaigns c
  set sent_count = (select count(*) from public.email_deliveries d where d.campaign_id = c.id and d.status in ('sent','delivered')),
      failed_count = (select count(*) from public.email_deliveries d where d.campaign_id = c.id and d.status = 'failed'),
      status = case when not exists (
        select 1 from public.email_deliveries d where d.campaign_id = c.id and d.status in ('pending','processing')
      ) then case when exists (
        select 1 from public.email_deliveries d where d.campaign_id = c.id and d.status in ('sent','delivered')
      ) then 'sent' else 'failed' end else c.status end,
      completed_at = case when not exists (
        select 1 from public.email_deliveries d where d.campaign_id = c.id and d.status in ('pending','processing')
      ) then now() else c.completed_at end,
      updated_at = now()
  where c.id = v_campaign_id;
end;
$$;

create or replace function public.rrg_claim_due_reminders(p_limit integer default 25)
returns table (
  reminder_id bigint, recipient_email text, goal_title text, county_name text,
  chapter_contact_email text
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.request_followup_reminders
  set status = 'failed', failed_at = now(), last_error_code = 'claim_timeout'
  where status = 'processing' and claimed_at < now() - interval '15 minutes' and attempt_count >= 3;

  return query
  with claimed as (
    select r.id
    from public.request_followup_reminders r
    where (r.status = 'pending' or (r.status = 'processing' and r.claimed_at < now() - interval '15 minutes'))
      and r.attempt_count < 3 and r.due_at <= now()
      and not exists (select 1 from public.email_suppressions s where s.email = r.email)
    order by r.due_at, r.id
    for update of r skip locked
    limit least(greatest(coalesce(p_limit, 25), 1), 100)
  ), updated as (
    update public.request_followup_reminders r
    set status = 'processing', claimed_at = now(), attempt_count = attempt_count + 1
    from claimed
    where r.id = claimed.id
    returning r.*
  )
  select u.id, u.email, g.title, c.name,
         coalesce(nullif(btrim(c.chapter_contact_email), ''), 'rerouter@flockblocktn.org')
  from updated u
  join public.county_records_request_goals g on g.id = u.goal_id
  join public.counties c on c.id = u.county_id;

  update public.request_followup_reminders r
  set status = 'suppressed'
  where r.status = 'pending' and r.due_at <= now()
    and exists (select 1 from public.email_suppressions s where s.email = r.email);
end;
$$;

create or replace function public.rrg_record_reminder_result(
  p_reminder_id bigint,
  p_sent boolean,
  p_provider_email_id text default null,
  p_error_code text default null
)
returns void
language sql
security definer
set search_path = ''
as $$
  update public.request_followup_reminders
  set status = case when p_sent then 'sent' else 'failed' end,
      provider_email_id = case when p_sent then p_provider_email_id else provider_email_id end,
      sent_at = case when p_sent then now() else sent_at end,
      failed_at = case when p_sent then failed_at else now() end,
      last_error_code = case when p_sent then null else left(coalesce(p_error_code, 'send_failed'), 80) end
  where id = p_reminder_id and status = 'processing';
$$;

create or replace function public.rrg_process_resend_webhook(
  p_event_id text,
  p_event_type text,
  p_provider_email_id text,
  p_recipient_email text default null
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_delivery public.email_deliveries%rowtype;
  v_email text := lower(btrim(p_recipient_email));
begin
  insert into public.email_webhook_events (event_id, event_type, provider_email_id)
  values (p_event_id, p_event_type, p_provider_email_id)
  on conflict (event_id) do nothing;
  if not found then return false; end if;

  select * into v_delivery
  from public.email_deliveries
  where provider_email_id = p_provider_email_id
  for update;

  if found then
    v_email := v_delivery.recipient_email;
    update public.email_deliveries
    set status = case
          when p_event_type = 'email.delivered' then 'delivered'
          when p_event_type = 'email.bounced' then 'bounced'
          when p_event_type = 'email.complained' then 'complained'
          else status end,
        delivered_at = case when p_event_type = 'email.delivered' then now() else delivered_at end,
        failed_at = case when p_event_type in ('email.bounced','email.complained') then now() else failed_at end
    where id = v_delivery.id;

    update public.email_campaigns c
    set delivered_count = (select count(*) from public.email_deliveries d where d.campaign_id = c.id and d.status = 'delivered'),
        bounced_count = (select count(*) from public.email_deliveries d where d.campaign_id = c.id and d.status = 'bounced'),
        complained_count = (select count(*) from public.email_deliveries d where d.campaign_id = c.id and d.status = 'complained'),
        updated_at = now()
    where c.id = v_delivery.campaign_id;
  end if;

  if p_event_type in ('email.bounced', 'email.complained') and v_email is not null then
    insert into public.email_suppressions (email, reason, source_event_id)
    values (v_email, case when p_event_type = 'email.complained' then 'complaint' else 'bounce' end, p_event_id)
    on conflict (email) do update
      set reason = excluded.reason, source_event_id = excluded.source_event_id, suppressed_at = now();
  end if;

  return true;
end;
$$;

