  complained_count integer not null default 0 check (complained_count >= 0),
  failed_count integer not null default 0 check (failed_count >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    (target_scope = 'global' and county_id is null)
    or (target_scope = 'county' and county_id is not null)
  ),
  check (
    (status = 'requested' and approved_by is null and approved_at is null and post_snapshot is null)
    or status in ('rejected', 'cancelled')
    or (approved_by is not null and approved_at is not null and jsonb_typeof(post_snapshot) = 'object')
