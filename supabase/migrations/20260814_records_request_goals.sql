create or replace function public.rrg_validate_goal_relationships()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  entity_county_id bigint;
  profile_entity_id bigint;
begin
  if new.government_entity_id is not null then
    select entity.county_id
    into entity_county_id
    from public.government_entities as entity
    where entity.id = new.government_entity_id;

    if entity_county_id is not null and entity_county_id <> new.county_id then
      raise exception 'The government entity does not belong to this county';
    end if;
  end if;

  if new.request_profile_id is not null then
    if new.government_entity_id is null then
      raise exception 'A request profile requires a government entity';
    end if;

    select profile.government_entity_id
    into profile_entity_id
    from public.request_profiles as profile
    where profile.id = new.request_profile_id;

    if profile_entity_id is distinct from new.government_entity_id then
      raise exception 'The request profile belongs to a different government entity';
    end if;
  end if;

  return new;
end;
$$;

