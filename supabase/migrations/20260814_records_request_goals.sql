create or replace function public.clone_records_request_goal_templates(
  target_county_id bigint,
  template_seed_keys text[] default null
)
returns integer
language plpgsql
security invoker
set search_path = ''
as $$
declare
  inserted_count integer;
begin
  if not public.rrg_can_manage_county(target_county_id) then
    raise exception 'You cannot manage this county';
  end if;

  insert into public.county_records_request_goals (
    county_id,
    goal_template_id,
    title,
    public_summary,
    fill_payload,
    status,
    position,
    is_public,
    created_by,
    updated_by
  )
  select
    target_county_id,
    template.id,
    template.title,
    template.public_summary,
    template.default_fill_payload,
    'profile_needed',
    template.default_position,
    false,
    auth.uid(),
    auth.uid()
  from public.records_request_goal_templates as template
  where template.active
    and (
      template_seed_keys is null
      or template.seed_key = any(template_seed_keys)
    )
  on conflict (county_id, goal_template_id)
    where goal_template_id is not null
  do nothing;

  get diagnostics inserted_count = row_count;
  return inserted_count;
end;
$$;

revoke all on function public.clone_records_request_goal_templates(bigint, text[])
  from public;
