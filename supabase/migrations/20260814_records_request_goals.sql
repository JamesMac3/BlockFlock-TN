create or replace function public.rrg_is_active_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(
    (
      select account.role = 'admin' and account.status = 'active'
      from public.portal_accounts as account
      where account.user_id = auth.uid()
    ),
    false
  );
$$;

create or replace function public.rrg_can_manage_county(requested_county_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(
    (
      select
        account.status = 'active'
        and (
          account.role = 'admin'
          or (
            account.role = 'chapter_master'
            and account.county_id = requested_county_id
          )
        )
      from public.portal_accounts as account
      where account.user_id = auth.uid()
    ),
    false
  );
$$;

create or replace function public.rrg_can_manage_goal(requested_goal_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(
    (
      select public.rrg_can_manage_county(goal.county_id)
      from public.county_records_request_goals as goal
      where goal.id = requested_goal_id
    ),
    false
  );
$$;

create or replace function public.rrg_goal_is_public(requested_goal_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.county_records_request_goals as goal
    where goal.id = requested_goal_id
      and goal.is_public
      and goal.status not in ('draft', 'retired')
  );
$$;

create or replace function public.rrg_evidence_is_public(requested_evidence_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select requested_evidence_id is not null
    and exists (
      select 1
      from public.evidence_objects as evidence
      where evidence.id = requested_evidence_id
        and evidence.status = 'published'
        and evidence.visibility = 'public'
    );
$$;

