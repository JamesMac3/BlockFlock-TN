create or replace function public.rrg_validate_link_relationships()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  goal_county_id bigint;
  evidence_county_id bigint;
begin
  if new.evidence_object_id is null then
    return new;
  end if;

  select goal.county_id
  into goal_county_id
  from public.county_records_request_goals as goal
  where goal.id = new.goal_id;

  select evidence.county_id
  into evidence_county_id
  from public.evidence_objects as evidence
  where evidence.id = new.evidence_object_id;

  if evidence_county_id is not null
     and evidence_county_id <> goal_county_id then
    raise exception 'The hosted document belongs to a different county';
  end if;

  return new;
end;
$$;

