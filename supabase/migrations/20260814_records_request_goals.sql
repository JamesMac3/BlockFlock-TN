create or replace function public.rrg_fill_payload_is_safe(payload jsonb)
returns boolean
language plpgsql
immutable
set search_path = ''
as $$
declare
  item jsonb;
begin
  if payload is null or jsonb_typeof(payload) <> 'object' then
    return false;
  end if;

  if (payload - array['request']) <> '{}'::jsonb then
    return false;
  end if;

  if not (payload ? 'request')
     or jsonb_typeof(payload -> 'request') <> 'object' then
    return false;
  end if;

  if (
    (payload -> 'request')
    - array[
        'records_description',
        'department_or_division',
        'record_category_label',
        'date_from_mm_dd_yyyy',
        'date_to_mm_dd_yyyy',
        'delivery_method'
      ]
  ) <> '{}'::jsonb then
    return false;
  end if;

  for item in
    select value
    from jsonb_each(payload -> 'request')
  loop
    if jsonb_typeof(item) not in ('string', 'null') then
      return false;
    end if;
  end loop;

  return true;
end;
$$;

comment on function public.rrg_fill_payload_is_safe(jsonb) is
  'Rejects personal or unrecognized fields from public request-goal fill data.';

